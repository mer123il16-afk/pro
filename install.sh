#!/usr/bin/env bash
# مثبّت واحد: يجهّز كل شيء ويشغّل المساعد. التشغيل:  bash install.sh
set -e
D="$HOME/assistant"; mkdir -p "$D/voices"
echo "[1/4] تجهيز الأدوات"
if [ -d /data/data/com.termux ]; then pkg update -y >/dev/null 2>&1 || true; pkg install -y python >/dev/null 2>&1 || true; fi
command -v python3 >/dev/null || { echo "ثبّت python3 أولًا"; exit 1; }
echo "[2/4] استخراج الملفات"
sed '1,/^__PAYLOAD__$/d' "$0" | base64 -d | tar xz -C "$D"
if command -v nvidia-smi >/dev/null 2>&1; then
  echo "[3/4] كرت شاشة NVIDIA موجود: تثبيت الصور والفيديو والصوت (قد يأخذ وقتًا)"
  python3 -m pip install -q torch diffusers transformers accelerate safetensors sentencepiece imageio imageio-ffmpeg pillow coqui-tts
  TOK=$(python3 -c "import secrets;print(secrets.token_urlsafe(18))")
  echo "$TOK" > "$D/gen_token.txt"
  python3 -c "import json,sys;json.dump({'gen_url':'http://127.0.0.1:8780','gen_token':sys.argv[1]},open('$D/config.json','w'))" "$TOK"
  GEN=1
else
  echo "[3/4] لا يوجد كرت NVIDIA هنا (الجوال مثلًا): تم تثبيت المساعد فقط."
  echo "     لتوليد الصور والفيديو والصوت شغّل نفس هذا السكربت على جهاز فيه كرت NVIDIA، ثم ضع عنوانه ورمزه في الإعدادات."
  GEN=0
fi
cat > "$D/start.sh" <<EOS
#!/usr/bin/env bash
cd "$D"
termux-wake-lock 2>/dev/null || true
if [ "$GEN" = "1" ]; then GEN_TOKEN=\$(cat gen_token.txt) python3 gen_server.py >gen.log 2>&1 & echo "المولّد يعمل (رمزه في gen_token.txt)"; fi
python3 assistant_server.py
EOS
grep -q "alias assistant=" ~/.bashrc 2>/dev/null || echo "alias assistant='bash $D/start.sh'" >> ~/.bashrc
echo "[4/4] تشغيل المساعد. افتح المتصفح على:  http://127.0.0.1:8765"
echo "ولاحقًا شغّله بكتابة:  assistant"
exec bash "$D/start.sh"
exit 0
